"use client";

import Markdown from "react-markdown";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { briefFiltersLabel } from "@/lib/exec/brief";
import { fmtDateTime, fmtShortDate } from "@/lib/format";
import type { components } from "@/lib/api/schema";

type ExecBriefOut = components["schemas"]["ExecBriefOut"];

interface ExecBriefModalProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  brief: ExecBriefOut | null;
  /** `manage_intel` dan brief yang tampil adalah brief hari ini (diputuskan halaman). */
  canRegenerate: boolean;
  onRegenerate: () => void;
  regenerating: boolean;
}

/** Unduh Markdown apa adanya sebagai berkas `.md` lewat Blob + anchor sementara. */
function downloadMarkdown(brief: ExecBriefOut) {
  const url = URL.createObjectURL(new Blob([brief.markdown], { type: "text/markdown;charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = `exec-brief-${brief.brief_date}.md`;
  a.click();
  URL.revokeObjectURL(url);
}

/** Dialog brief penuh (6.3). Selalu menampilkan seluruh Markdown lewat `react-markdown`, tidak bergantung
 * pada parser kartu, jadi balasan LLM yang bentuknya tak terduga tetap terbaca utuh. */
export function ExecBriefModal({ open, onOpenChange, brief, canRegenerate, onRegenerate, regenerating }: ExecBriefModalProps) {
  return (
    <Dialog open={open && brief !== null} onOpenChange={onOpenChange}>
      <DialogContent className="w-full sm:max-w-2xl">
        <DialogHeader>
          <DialogTitle>Executive brief</DialogTitle>
          {brief && (
            <DialogDescription>
              {fmtShortDate(brief.brief_date, { withYear: true })} · {briefFiltersLabel(brief.filters)} · generated by{" "}
              {brief.generated_by} · {fmtDateTime(brief.generated_at)}
            </DialogDescription>
          )}
        </DialogHeader>
        <div className="prose prose-sm max-h-[55vh] max-w-none overflow-y-auto pr-1 text-xs leading-relaxed">
          <Markdown>{brief?.markdown ?? ""}</Markdown>
        </div>
        <DialogFooter className="sm:items-center">
          <p className="text-2xs text-muted-foreground sm:mr-auto">AI draft. Review before sharing.</p>
          <Button variant="outline" disabled={!brief} onClick={() => brief && downloadMarkdown(brief)}>
            Download .md
          </Button>
          <Button
            variant="outline"
            disabled={!brief}
            onClick={() => {
              if (!brief) return;
              navigator.clipboard.writeText(brief.markdown).then(
                () => toast.success("Copied to clipboard"),
                () => toast.error("Could not copy to clipboard"),
              );
            }}
          >
            Copy
          </Button>
          {canRegenerate && (
            <Button loading={regenerating} onClick={onRegenerate}>
              {regenerating ? "Regenerating…" : "Regenerate"}
            </Button>
          )}
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
